/** Answerable required fields for a form: required, not a note, not a
 *  5-year timeline field, not sensitive. These are the fields that
 *  must be answered before the form counts as complete. */
export function answerableRequiredFields(formCode: string): RegistryField[] {
  const schema = getRegistrySchema(formCode);
  if (!schema) return [];
  return requiredFieldsForSchemas([schema])
    .filter((f) => f.field.type !== "timeline_5yr" && f.field.sensitive !== true)
    .map((f) => f.field);
}

/** Required fields that can never be answered from a draft. */
export function transferBlockedFields(formCode: string): {
  mustEnterOnForm: RegistryField[];
  timelineFields: RegistryField[];
} {
  const schema = getRegistrySchema(formCode);
  if (!schema) return { mustEnterOnForm: [], timelineFields: [] };
  const required = requiredFieldsForSchemas([schema]).map((f) => f.field);
  return {
    mustEnterOnForm: required.filter((f) => f.sensitive === true),
    timelineFields: required.filter((f) => f.type === "timeline_5yr"),
  };
}

export interface DiyCompletionStatus {
  formCode: string;
  complete: boolean;
  answeredCount: number;
  totalCount: number;
  progressPercent: number;
  /** Required answerable questions with no answer yet. */
  missing: RegistryField[];
  /** Required sensitive fields — re-enter on the official form. */
  mustEnterOnForm: RegistryField[];
  /** Required timeline fields — checked separately. */
  timelineFields: RegistryField[];
}

/** Completion of a draft: answered / total over answerable required
 *  fields only. Sensitive + timeline fields are reported, never
 *  counted as missing answers. Unknown formCode = not complete. */
export function diyCompletionStatus(
  formCode: string,
  answers: DiyDraftAnswers
): DiyCompletionStatus {
  const schema = getRegistrySchema(formCode);
  const total = answerableRequiredFields(formCode);
  const { mustEnterOnForm, timelineFields } = transferBlockedFields(formCode);
  if (!schema) {
    return {
      formCode,
      complete: false,
      answeredCount: 0,
      totalCount: 0,
      progressPercent: 0,
      missing: [],
      mustEnterOnForm,
      timelineFields,
    };
  }
  const missing = total.filter((f) => !((answers[f.name] ?? "").trim()));
  const answeredCount = total.length - missing.length;
  return {
    formCode,
    complete: missing.length === 0,
    answeredCount,
    totalCount: total.length,
    progressPercent:
      total.length > 0 ? Math.round((answeredCount / total.length) * 100) : 100,
    missing,
    mustEnterOnForm,
    timelineFields,
  };
}

/** Resume position: the exact question the client left off — the
 *  first unanswered answerable required field, in schema order
 *  (section index, question index within that section, field name).
 *  When everything is answered, the position is the last question
 *  (the review step), never past the end. Null when the form has no
 *  schema. */
export function resumePositionFor(
  formCode: string,
  answers: DiyDraftAnswers
): { sectionIndex: number; questionIndex: number; fieldName: string } | null {
  const schema = getRegistrySchema(formCode);
  if (!schema) return null;
  let lastField: { sectionIndex: number; questionIndex: number; fieldName: string } | null = null;
  for (let s = 0; s < schema.sections.length; s += 1) {
    const section = schema.sections[s];
    let q = 0;
    for (const field of section.fields) {
      if (field.type === "note") continue;
      const pos = { sectionIndex: s, questionIndex: q, fieldName: field.name };
      lastField = pos;
      if (
        field.required &&
        field.type !== "timeline_5yr" &&
        field.sensitive !== true &&
        !((answers[field.name] ?? "").trim())
      ) {
        return pos;
      }
      q += 1;
    }
  }
  return lastField;
}

