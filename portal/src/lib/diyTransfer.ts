/**
 * KEY BRIDGE — why this table exists: the guided DIY flow saves
 * answers under the REGISTRY's question keys (e.g.
 * `i130_petitioner_full_name`), while src/lib/uscisFieldMappings.ts
 * still uses the OLD questionnaire keys from migration 0005
 * (e.g. `petitioner_full_name`). The two namespaces only partly
 * overlap, so a transfer that looked up exact keys only would fill
 * almost nothing and silently report the rest as unanswered.
 *
 * Each alias below is a VERBATIM carry-over — the same question, the
 * same meaning, only the key spelling differs. The value is copied
 * exactly as the client typed it; nothing is joined, reformatted or
 * inferred. Keys with NO safe verbatim source are NOT aliased:
 *   * `marriage_date_place` — the registry asks date and place as
 *     TWO questions (`i130_marriage_date` + `i130_marriage_place`);
 *     joining them into one string would invent a format.
 *   * `petitioner_address_history_5y` / `i751_shared_addresses` —
 *     5-year timelines, not text answers.
 *   * `i131_trip_purpose` — aliased to the client's own words
 *     (`i131_travel_purpose_detail` first, else the select value
 *     `i131_travel_purpose`); both are the client's answer to the
 *     same "why do you need to travel?" question.
 *   * `i539_action_type`, `i539_current_status_code`,
 *     `i539_requested_until`, `i129f_how_met` — no verified verbatim
 *     source in the registry; they stay unmapped and are listed as
 *     such, never guessed.
 * Every transferred field records its `sourceKey` and whether it was
 * aliased, so the transfer result shows exactly where each value
 * came from. Reconciling the two namespaces properly (one canonical
 * key per question) belongs to the mappings owner, not this file.
 */
export const DIY_TRANSFER_KEY_ALIASES: Record<string, string[]> = {
  petitioner_full_name: ["i130_petitioner_full_name"],
  beneficiary_full_name: ["i130_beneficiary_full_name"],
  beneficiary_passport_number: ["i130_beneficiary_passport_number"],
  i131_applicant_name: ["i131_applicant_full_name"],
  i131_trip_purpose: ["i131_travel_purpose_detail", "i131_travel_purpose"],
  i751_conditional_resident_name: ["i751_petitioner_full_name"],
  i751_filing_basis: ["i751_filing_type"],
  i751_petitioning_spouse_name: ["i751_spouse_name"],
  i539_applicant_name: ["i539_applicant_full_name"],
  i129f_petitioner_name: ["i129f_petitioner_full_name"],
  i129f_fiance_name: ["i129f_beneficiary_full_name"],
};

/** Resolve one mapping key to a saved answer: the exact key first,
 *  then the alias candidates in order. Returns the value and the key
 *  it actually came from (null when nothing was saved for it). */
export function resolveTransferValue(
  questionKey: string,
  answers: DiyDraftAnswers
): { value: string; sourceKey: string | null; aliased: boolean } {
  const exact = (answers[questionKey] ?? "").trim();
  if (exact) return { value: answers[questionKey], sourceKey: questionKey, aliased: false };
  for (const alias of DIY_TRANSFER_KEY_ALIASES[questionKey] ?? []) {
    const v = (answers[alias] ?? "").trim();
    if (v) return { value: answers[alias], sourceKey: alias, aliased: true };
  }
  return { value: "", sourceKey: null, aliased: false };
}

export interface TransferredField {
  questionKey: string;
  fieldLabel: string;
  acroFormFieldName: string;
  /** Always "UNVERIFIED" — see src/lib/uscisFieldMappings.ts. */
  mappingStatus: "UNVERIFIED";
  verified: false;
  /** The saved answer value (masked in display, never logged). */
  value: string;
  /** True when the answer was present in the draft. */
  answered: boolean;
  /** The draft key the value actually came from (the mapping key
   *  itself, or an alias from DIY_TRANSFER_KEY_ALIASES). */
  sourceKey: string | null;
  /** True when the value came from an alias key, not the exact key. */
  aliased: boolean;
}

export interface DiyTransferResult {
  formCode: string;
  complete: boolean;
  /** Mapped fields: one row per USCIS mapping for this form, with
   *  the saved answer (or empty + answered=false when unanswered). */
  mappedFields: TransferredField[];
  /** Saved answers with no USCIS mapping — listed, never dropped. */
  unmappedAnswers: { questionKey: string; value: string }[];
  /** Required questions still unanswered — transfer must not run. */
  missing: RegistryField[];
  mustEnterOnForm: RegistryField[];
  timelineFields: RegistryField[];
  notice: string;
  editionReminder: string;
}

/**
 * Transfer a (sanitized) draft's answers into the form's USCIS field
 * mappings. Pure — no I/O, no packet generation. Returns
 * complete=false with the missing list when the form is not complete;
 * callers must not generate a packet from an incomplete transfer.
 */
export function transferAnswersToForm(
  formCode: string,
  rawAnswers: DiyDraftAnswers
): DiyTransferResult {
  const { answers } = sanitizeDraftAnswers(rawAnswers);
  const completion = diyCompletionStatus(formCode, answers);
  const mappings = mappingsForForm(formCode);
  const mappedKeys = new Set(mappings.map((m) => m.questionKey));
  // Keys consumed by the transfer (mapping keys + alias source keys)
  // are not "unmapped" — only genuinely unclaimed answers are listed.
  const consumedKeys = new Set<string>(mappedKeys);
  const mappedFields: TransferredField[] = mappings.map((m) => {
    const resolved = resolveTransferValue(m.questionKey, answers);
    for (const alias of DIY_TRANSFER_KEY_ALIASES[m.questionKey] ?? []) {
      consumedKeys.add(alias);
    }
    return {
      questionKey: m.questionKey,
      fieldLabel: m.fieldLabel,
      acroFormFieldName: m.acroFormFieldName,
      mappingStatus: "UNVERIFIED" as const,
      verified: false as const,
      value: resolved.value,
      answered: Boolean(resolved.value.trim()),
      sourceKey: resolved.sourceKey,
      aliased: resolved.aliased,
    };
  });
  const unmappedAnswers = Object.entries(answers)
    .filter(([key, value]) => !consumedKeys.has(key) && value.trim() !== "")
    .map(([questionKey, value]) => ({ questionKey, value }));
  return {
    formCode,
    complete: completion.complete,
    mappedFields,
    unmappedAnswers,
    missing: completion.missing,
    mustEnterOnForm: completion.mustEnterOnForm,
    timelineFields: completion.timelineFields,
    notice: DIY_TRANSFER_NOTICE,
    editionReminder: DIY_EDITION_REMINDER,
  };
}

