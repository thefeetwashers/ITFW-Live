// Automatic answer transfer on DIY completion — pure logic, no I/O.
//
// FOUNDER'S ADDITION (Nov 28, 2026): once the client has answered
// ALL the questions, the system AUTOMATICALLY transfers their answers
// into the immigration form and lets them print, save, and more.
//
// HOW THE TRANSFER WORKS (nothing rebuilt here):
//   * Completion is decided from the form's registry schema
//     (src/lib/dynamicIntakeSchemas.ts): every REQUIRED field must
//     have an answer. Two field kinds never block completion and are
//     listed separately, honestly:
//       - SENSITIVE required fields (SSN / A-Number / passport /
//         green-card number): the draft NEVER holds them (migration
//         0023 trigger + src/lib/diyDrafts.ts). They are listed as
//         `mustEnterOnForm` — the client re-enters them on the
//         official form itself. A form is NOT called incomplete
//         because the draft correctly refused to store a passport
//         number.
//       - 5-YEAR TIMELINE fields: answered in the engine's Timeline
//         Builder, not as a text answer. They are listed as
//         `timelineFields` and checked separately — the packet route
//         blocks on timeline gaps, this module never pretends the
//         timeline is complete from answers alone.
//   * The transfer itself REUSES the existing mappings —
//     src/lib/uscisFieldMappings.ts (mappingsForForm). Every mapping
//     stays UNVERIFIED (AcroForm names are guesses until checked
//     against the real USCIS PDF for the edition); the transfer
//     output carries that status on every row and never claims a
//     form is filled just because a mapping entry exists. Answers
//     with no mapping are listed as `unmappedAnswers`, never
//     silently dropped.
//   * The packet PDF is generated by the EXISTING
//     POST /api/generate-packet route (called by
//     POST /api/diy/transfer and POST /api/diy/packet) — it keeps its
//     own gates: DRAFT watermark + cover sheet, 100% packet audit,
//     balance paid, only review_status='accepted' documents
//     included, honest 404 when the USCIS template is missing.
//     A transfer that succeeds does NOT mean a packet was generated:
//     the route reports the packet attempt separately.
//   * "And more" after transfer REUSES the DIY builder's
//     src/lib/diySubmission.ts — the document checklist
//     (checklistTitlesForForm), the draft cover letter
//     (buildDiyCoverLetter) and the submission-order guide
//     (submissionGuideForForms: which form, G-1450 card or G-1650
//     ACH only, online vs paper, in what order — with "confirm the
//     current fee/address at uscis.gov before you pay/send"). No
//     filing address is invented anywhere: none is stored in this
//     codebase. This file does NOT rebuild any of those three.
//   * Fee breakdown comes from src/lib/diyFees.ts (locked DIY
//     $25/form / $99 bundle + locked vs TO BE CONFIRMED gov lines).
//
// HARD RULES (kept, not weakened):
//   * Document-preparation service only — NOT a law firm, NOT USCIS
//     affiliated. Only a licensed attorney or DOJ-accredited
//     representative gives legal advice (8 CFR 292.1). No AI here
//     decides relief, eligibility, evidence strength, or whether it
//     is safe to travel / safe to file.
//   * The system never files for the client. The client reviews and
//     signs before anything is submitted. Every form carries its
//     USCIS edition notice ("check uscis.gov before filing").
//   * Never store SSNs; DOB / A-Number / passport masked, never logged.
//     This module never logs an answer value — only question keys
//     and counts.

